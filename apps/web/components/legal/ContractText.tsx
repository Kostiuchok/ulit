const INLINE_RE = /\*\*(.+?)\*\*|\[(.+?)\]\((.+?)\)/g;

function renderInline(text: string): ReactNode[] {
  const out: ReactNode[] = [];
  let last = 0;
  const re = new RegExp(INLINE_RE.source, "g");
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) {
    const i = m.index;
    if (i > last) out.push(text.slice(last, i));
    if (m[1] !== undefined) {
      out.push(<strong key={i}>{m[1]}</strong>);
    } else {
      out.push(
        <a key={i} href={m[3]} className="text-blue-600 hover:underline">
          {m[2]}
        </a>
      );
    }
    last = i + m[0].length;
  }
  if (last < text.length) out.push(text.slice(last));
  return out;
}

function plainInline(text: string): string {
  return text.replace(INLINE_RE, (_m, bold?: string, linkText?: string) => bold ?? linkText ?? "");
}

function BlockView({ block }: { block: Block }) {
  if (typeof block === "string") return <p>{renderInline(block)}</p>;
  const list = (
    <ul className="list-disc list-inside space-y-1.5 ml-4">
      {block.list.map((item, i) => (
        <li key={i}>{renderInline(item)}</li>
      ))}
    </ul>
  );
  if ("lead" in block) {
    return (
      <>
        <p>{renderInline(block.lead)}</p>
        {list}
      </>
    );
  }
  return list;
}

